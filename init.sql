-- 汽车租赁系统数据库初始化脚本（扩充版 - 35辆车）
CREATE DATABASE IF NOT EXISTS car_rental DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE car_rental;

-- 用户表
DROP TABLE IF EXISTS `users`;
CREATE TABLE `users` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `username` VARCHAR(50) NOT NULL UNIQUE,
  `password` VARCHAR(100) NOT NULL,
  `nickname` VARCHAR(50) DEFAULT NULL,
  `phone` VARCHAR(20) DEFAULT NULL,
  `email` VARCHAR(100) DEFAULT NULL,
  `avatar` LONGTEXT DEFAULT NULL COMMENT '用户头像(base64)',
  `role` TINYINT NOT NULL DEFAULT 0 COMMENT '0普通用户 1管理员',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 车辆表
DROP TABLE IF EXISTS `cars`;
CREATE TABLE `cars` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `brand` VARCHAR(50) NOT NULL,
  `model` VARCHAR(50) NOT NULL,
  `color` VARCHAR(20) DEFAULT NULL,
  `seats` INT NOT NULL DEFAULT 5,
  `price_per_day` DECIMAL(10,2) NOT NULL,
  `deposit` DECIMAL(10,2) NOT NULL DEFAULT 0,
  `image` VARCHAR(255) DEFAULT '/img/default-car.png',
  `status` TINYINT NOT NULL DEFAULT 0 COMMENT '0空闲 1已租 2已预约 3维护中',
  `mileage` INT NOT NULL DEFAULT 0 COMMENT '总行驶里程(km)',
  `maintain_count` INT NOT NULL DEFAULT 0 COMMENT '保养次数',
  `last_maintain_date` DATE DEFAULT NULL,
  `description` TEXT,
  `category` VARCHAR(30) DEFAULT '轿车' COMMENT '轿车/SUV/MPV/新能源',
  `usage_type` VARCHAR(50) DEFAULT NULL COMMENT '用途类型：商务/婚庆/家庭/通勤/旅游，逗号分隔',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 订单表
DROP TABLE IF EXISTS `orders`;
CREATE TABLE `orders` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `order_no` VARCHAR(32) NOT NULL UNIQUE,
  `user_id` BIGINT NOT NULL,
  `car_id` BIGINT NOT NULL,
  `driver_id` BIGINT DEFAULT NULL COMMENT '司机ID（可选）',
  `start_time` DATETIME NOT NULL,
  `end_time` DATETIME NOT NULL,
  `actual_return_time` DATETIME DEFAULT NULL,
  `total_cost` DECIMAL(10,2) DEFAULT 0,
  `driver_cost` DECIMAL(10,2) DEFAULT 0 COMMENT '司机服务费',
  `deposit` DECIMAL(10,2) NOT NULL DEFAULT 0,
  `deposit_refund` DECIMAL(10,2) DEFAULT 0 COMMENT '押金退还金额',
  `status` TINYINT NOT NULL DEFAULT 0 COMMENT '0待支付 1在租 2已完成 3已取消 4预约中 5已退款',
  `remark` VARCHAR(255) DEFAULT NULL COMMENT '订单备注',
  `user_rating` TINYINT DEFAULT NULL COMMENT '用户评分1-5',
  `user_comment` VARCHAR(500) DEFAULT NULL COMMENT '用户评价',
  `start_mileage` INT DEFAULT NULL COMMENT '取车时里程(km)',
  `end_mileage` INT DEFAULT NULL COMMENT '还车时里程(km)',
  `mileage_driven` INT DEFAULT NULL COMMENT '本次行驶里程(km)',
  `discount` DECIMAL(10,2) DEFAULT 0 COMMENT '优惠金额',
  `deposit_paid` TINYINT DEFAULT 0 COMMENT '押金是否已支付 0未付 1已付',
  `rental_paid` TINYINT DEFAULT 0 COMMENT '租金是否已支付 0未付 1已付',
  `deposit_paid_time` DATETIME DEFAULT NULL COMMENT '押金支付时间',
  `rental_paid_time` DATETIME DEFAULT NULL COMMENT '租金支付时间',
  `cancel_time` DATETIME DEFAULT NULL COMMENT '取消时间',
  `pickup_confirmed` TINYINT DEFAULT 0 COMMENT '是否确认取车 0未确认 1已确认',
  `pickup_time` DATETIME DEFAULT NULL COMMENT '确认取车时间',
  `pickup_warning_sent` TINYINT DEFAULT 0 COMMENT '是否已发送2h取车警告 0未发送 1已发送',
  `pickup_store_id` BIGINT DEFAULT NULL COMMENT '取车门店ID',
  `return_store_id` BIGINT DEFAULT NULL COMMENT '还车门店ID',
  `pickup_city` VARCHAR(20) DEFAULT NULL COMMENT '取车城市',
  `return_city` VARCHAR(20) DEFAULT NULL COMMENT '还车城市',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_car_id` (`car_id`),
  KEY `idx_driver_id` (`driver_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 维护记录表
DROP TABLE IF EXISTS `maintenance_records`;
CREATE TABLE `maintenance_records` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `car_id` BIGINT NOT NULL,
  `mileage_at_maintenance` INT NOT NULL,
  `maintenance_type` VARCHAR(50) NOT NULL,
  `description` TEXT,
  `cost` DECIMAL(10,2) DEFAULT 0,
  `maintenance_date` DATE NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_car_id` (`car_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 门店表（渝贵川区域）
DROP TABLE IF EXISTS `stores`;
CREATE TABLE `stores` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(50) NOT NULL COMMENT '门店名称',
  `city` VARCHAR(20) NOT NULL COMMENT '城市',
  `address` VARCHAR(200) NOT NULL COMMENT '详细地址',
  `phone` VARCHAR(20) COMMENT '联系电话',
  `longitude` DECIMAL(10,7) COMMENT '经度',
  `latitude` DECIMAL(10,7) COMMENT '纬度',
  `status` TINYINT DEFAULT 1 COMMENT '0关闭 1营业中 2休息',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_city` (`city`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

