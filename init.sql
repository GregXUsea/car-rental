-- 司机表
DROP TABLE IF EXISTS `drivers`;
CREATE TABLE `drivers` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(50) NOT NULL,
  `phone` VARCHAR(20) NOT NULL,
  `id_card` VARCHAR(20) DEFAULT NULL COMMENT '身份证号',
  `license_type` VARCHAR(20) DEFAULT NULL COMMENT '驾照类型：C1/C2/B1/B2/A1/A2',
  `license_expire_date` DATE DEFAULT NULL COMMENT '驾照到期日',
  `experience_years` INT DEFAULT 0 COMMENT '驾龄（年）',
  `avatar` LONGTEXT DEFAULT NULL COMMENT '司机头像(base64)',
  `status` TINYINT NOT NULL DEFAULT 0 COMMENT '0空闲 1服务中 2休假 3离职',
  `rating` DECIMAL(3,2) DEFAULT 5.00 COMMENT '评分',
  `service_count` INT DEFAULT 0 COMMENT '服务次数',
  `description` TEXT COMMENT '简介',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_phone` (`phone`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 验证码表（用于邮箱找回密码）
DROP TABLE IF EXISTS `verification_codes`;
CREATE TABLE `verification_codes` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `user_id` BIGINT NOT NULL,
  `email` VARCHAR(100) NOT NULL,
  `code` VARCHAR(10) NOT NULL,
  `used` TINYINT NOT NULL DEFAULT 0 COMMENT '0未使用 1已使用',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `expire_time` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_email` (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

